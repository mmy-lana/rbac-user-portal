import {
  ForbiddenException,
  Inject,
  Injectable,
  UnauthorizedException,
} from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import * as bcrypt from 'bcrypt';
import * as crypto from 'node:crypto';
import { and, eq, users, rolePermissions, permissions } from '@rbac/database';
import { DatabaseService } from '../database/database.service';
import { UsersService, type UserWithSecrets } from '../users/users.service';
import { AuditService } from '../audit/audit.service';
import { APP_ENV, type AppEnvironment } from '../../config/env';
import type { RefreshSession } from '../../common/interfaces/request.interface';
import {
  ALL_PERMISSIONS,
  SystemRole,
  UserStatus,
  type AuthenticatedUserPayload,
  type MeResponseDto,
  type Permission,
} from '@rbac/shared';

/** bcrypt work factor mandated for every credential digest. */
export const BCRYPT_SALT_ROUNDS = 12;

/** Refresh token entropy: 64 random bytes rendered as hex (512 bits). */
const REFRESH_TOKEN_SECRET_BYTES = 64;

/** Separator between the lookup prefix and the secret part of a refresh token. */
const REFRESH_TOKEN_SEPARATOR = '.';

/** User ids are generated by this codebase as `usr_<uuid>`. */
const USER_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

/**
 * A valid bcrypt digest of a value nobody can supply, used to burn comparable
 * CPU time when an unknown address attempts to authenticate.
 */
const DUMMY_PASSWORD_HASH =
  '$2b$12$C6UzMDM.H6dfI/f/IKcEe.e7tZTCxCxb6Z0FhE6nlqJZ0Qp0Z4iAe';

/** Request attribution carried into the audit trail. */
export interface RequestTelemetry {
  ipAddress: string;
  userAgent: string;
}

/**
 * Attribution for events raised outside a request cycle — for example a refresh
 * rotation triggered by the strategy with no telemetry attached.
 */
const SYSTEM_TELEMETRY: RequestTelemetry = {
  ipAddress: '127.0.0.1',
  userAgent: 'vault-session-sweeper',
};

/** Minimal session-bearing projection of a user row. */
type RefreshCandidate = UserWithSecrets & { refreshTokenHash: string };

export interface LoginResult {
  accessToken: string;
  refreshToken: string;
  expiresIn: number;
  principal: AuthenticatedUserPayload;
  user: MeResponseDto;
}

@Injectable()
export class AuthService {
  constructor(
    private readonly usersService: UsersService,
    private readonly jwtService: JwtService,
    private readonly dbService: DatabaseService,
    private readonly auditService: AuditService,
    @Inject(APP_ENV) private readonly env: AppEnvironment
  ) {}

  /**
   * Verifies credentials.
   *
   * Every credential failure returns the same `UnauthorizedException`, and an
   * unknown address still pays for one bcrypt comparison, so neither response
   * timing nor response body can be used to enumerate registered accounts.
   */
  async validateUserCredentials(
    email: string,
    password: string,
    telemetry: RequestTelemetry
  ): Promise<UserWithSecrets> {
    const normalizedEmail = email.trim().toLowerCase();
    const user = await this.usersService.findByEmail(normalizedEmail);

    if (!user) {
      await bcrypt.compare(password, DUMMY_PASSWORD_HASH);
      await this.auditService.recordSignIn({
        userId: 'unknown',
        role: SystemRole.MEMBER,
        outcome: 'failure',
        attemptedEmail: normalizedEmail,
        telemetry,
      });
      throw new UnauthorizedException('Authentication credentials invalid');
    }

    const matches = await bcrypt.compare(password, user.passwordHash);
    if (!matches) {
      await this.auditService.recordSignIn({
        userId: user.id,
        role: user.role ?? SystemRole.MEMBER,
        outcome: 'failure',
        attemptedEmail: normalizedEmail,
        telemetry,
      });
      throw new UnauthorizedException('Authentication credentials invalid');
    }

    if (user.status !== UserStatus.ACTIVE) {
      await this.auditService.recordSignIn({
        userId: user.id,
        role: user.role ?? SystemRole.MEMBER,
        outcome: 'failure',
        attemptedEmail: normalizedEmail,
        telemetry,
      });
      throw new ForbiddenException(
        user.status === UserStatus.SUSPENDED
          ? 'This identity is suspended.'
          : 'This identity has not completed activation.'
      );
    }

    await this.auditService.recordSignIn({
      userId: user.id,
      role: user.role ?? SystemRole.MEMBER,
      outcome: 'success',
      telemetry,
    });

    return user;
  }

  /**
   * Resolves the permissions granted to a role.
   *
   * `OWNER` short-circuits to `ALL_PERMISSIONS` imported from `@rbac/shared`, so
   * the root identity can never be locked out by a missing `role_permissions`
   * row and the JWT keeps the literal permission tuple instead of widening to
   * `string[]`.
   */
  async resolvePermissions(roleId: string, role: SystemRole): Promise<Permission[]> {
    if (role === SystemRole.OWNER) {
      return ALL_PERMISSIONS;
    }

    const granted = await this.dbService.db
      .select({ action: permissions.action })
      .from(rolePermissions)
      .innerJoin(permissions, eq(rolePermissions.permissionId, permissions.id))
      .where(eq(rolePermissions.roleId, roleId));

    return granted.map((row) => row.action as Permission);
  }

  /**
   * Issues a session for an authenticated user.
   *
   * The refresh token is generated with `crypto.randomBytes` — never
   * `Math.random`, which is not a CSPRNG — and only its bcrypt digest reaches
   * the database, so a database disclosure yields no usable session.
   */
  async createSession(user: UserWithSecrets): Promise<LoginResult> {
    const principal = await this.buildPrincipal(user);
    const accessToken = this.signAccessToken(principal);

    const refreshToken = this.generateRefreshToken(user.id);
    const stored = await this.persistRefreshToken(user.id, refreshToken);
    if (!stored) {
      throw new UnauthorizedException('Unable to establish a session for this identity.');
    }

    return {
      accessToken,
      refreshToken,
      expiresIn: this.env.accessTokenTtlSeconds,
      principal,
      user: await this.getMe(user.id),
    };
  }

  /**
   * Single-use refresh rotation.
   *
   * The digest swap is a conditional `UPDATE ... WHERE id = ? AND
   * refresh_token_hash = ?`. If the same token is presented twice — sequentially
   * or from two concurrent requests — the second statement matches zero rows,
   * the session is terminated, and the caller is rejected. That is the replay
   * detection the dual-token standard requires.
   */
  async rotateRefreshSession(
    presentedToken: string,
    telemetry?: RequestTelemetry
  ): Promise<RefreshSession> {
    const userId = this.readRefreshTokenSubject(presentedToken);
    if (userId === null) {
      throw new UnauthorizedException('Refresh credential is not recognised.');
    }

    const user = await this.findUserWithRefreshDigest(userId);
    if (!user) {
      throw new UnauthorizedException('Refresh credential is not recognised.');
    }

    const matches = await bcrypt.compare(presentedToken, user.refreshTokenHash);
    if (!matches) {
      await this.terminateSession(userId);
      await this.auditService.recordSessionTerminated({
        userId,
        reason: 'credential_invalid',
        telemetry: telemetry ?? SYSTEM_TELEMETRY,
      });
      throw new UnauthorizedException('Refresh credential is not recognised.');
    }

    const nextRefreshToken = this.generateRefreshToken(userId);
    const rotated = await this.persistRefreshToken(userId, nextRefreshToken, user.refreshTokenHash);
    if (!rotated) {
      await this.terminateSession(userId);
      await this.auditService.recordSessionTerminated({
        userId,
        reason: 'refresh_reuse_detected',
        telemetry: telemetry ?? SYSTEM_TELEMETRY,
      });
      throw new UnauthorizedException('Refresh credential has already been used.');
    }

    const principal = await this.buildPrincipal(user);
    return {
      principal,
      refreshToken: nextRefreshToken,
      accessToken: this.signAccessToken(principal),
      expiresIn: this.env.accessTokenTtlSeconds,
    };
  }

  /**
   * Issues a session for an identity that was just provisioned by another flow
   * (invitation acceptance), where the caller already holds a freshly persisted
   * user id rather than a loaded record.
   */
  async createSessionById(userId: string): Promise<LoginResult> {
    const user = await this.usersService.findAuthRecordById(userId);
    if (!user) {
      throw new UnauthorizedException('Identity could not be loaded for session issuance.');
    }
    return this.createSession(user);
  }

  /** Resolves `/me`: the caller's profile plus the effective permission list. */
  async getMe(userId: string): Promise<MeResponseDto> {
    const user = await this.usersService.findById(userId);
    if (!user) {
      throw new UnauthorizedException('Identity no longer exists.');
    }

    return {
      ...user,
      permissions: await this.resolvePermissions(user.roleId, user.role),
    };
  }

  /** Revokes the stored refresh digest, immediately ending the session. */
  async terminateSession(userId: string): Promise<void> {
    await this.dbService.db
      .update(users)
      .set({ refreshTokenHash: null, updatedAt: new Date() })
      .where(eq(users.id, userId));
  }

  /** Logout: terminates the session and records the actor's intent. */
  async terminateSessionForActor(
    userId: string,
    reason: 'logout' | 'refresh_reuse_detected' | 'credential_invalid',
    telemetry: RequestTelemetry
  ): Promise<void> {
    await this.terminateSession(userId);
    await this.auditService.recordSessionTerminated({ userId, reason, telemetry });
  }

  /**
   * Mints `<userId>.<512 bits of CSPRNG>`.
   *
   * The prefix is a lookup hint, not a secret: it identifies which digest to
   * compare against without scanning and comparing every account. The secret
   * half is what the bcrypt digest actually protects.
   */
  private generateRefreshToken(userId: string): string {
    const secret = crypto.randomBytes(REFRESH_TOKEN_SECRET_BYTES).toString('hex');
    return `${userId}${REFRESH_TOKEN_SEPARATOR}${secret}`;
  }

  /** Extracts the user id from a refresh token without trusting its contents. */
  private readRefreshTokenSubject(token: string): string | null {
    const separator = token.indexOf(REFRESH_TOKEN_SEPARATOR);
    if (separator <= 0) return null;

    const subject = token.slice(0, separator);
    const secret = token.slice(separator + 1);
    if (!USER_ID_PATTERN.test(subject)) return null;
    if (secret.length < REFRESH_TOKEN_SECRET_BYTES * 2) return null;

    return subject;
  }

  private signAccessToken(principal: AuthenticatedUserPayload): string {
    return this.jwtService.sign(
      {
        sub: principal.userId,
        email: principal.email,
        role: principal.role,
        permissions: principal.permissions,
      },
      {
        secret: this.env.jwtAccessSecret,
        expiresIn: this.env.accessTokenTtlSeconds,
      }
    );
  }

  private async buildPrincipal(user: UserWithSecrets): Promise<AuthenticatedUserPayload> {
    if (user.role === null) {
      throw new UnauthorizedException('Identity has no resolvable system role.');
    }

    return {
      userId: user.id,
      email: user.email,
      role: user.role,
      permissions: await this.resolvePermissions(user.roleId, user.role),
    };
  }

  /**
   * Stores a fresh refresh digest and stamps the login timestamp.
   *
   * When `expectedHash` is supplied the update is conditional, which is what
   * makes rotation single-use. Returns whether exactly one row was consumed.
   */
  private async persistRefreshToken(
    userId: string,
    refreshToken: string,
    expectedHash?: string
  ): Promise<boolean> {
    const refreshTokenHash = await bcrypt.hash(refreshToken, BCRYPT_SALT_ROUNDS);
    const now = new Date();

    const condition =
      expectedHash === undefined
        ? eq(users.id, userId)
        : and(eq(users.id, userId), eq(users.refreshTokenHash, expectedHash));

    const updated = await this.dbService.db
      .update(users)
      .set({ refreshTokenHash, lastLoginAt: now, updatedAt: now })
      .where(condition)
      .returning({ id: users.id });

    return updated.length > 0;
  }

  /** Loads a user that currently holds a refresh digest, with its role joined. */
  private async findUserWithRefreshDigest(userId: string): Promise<RefreshCandidate | undefined> {
    const record = await this.usersService.findAuthRecordById(userId);
    if (!record || record.refreshTokenHash === null) return undefined;
    return { ...record, refreshTokenHash: record.refreshTokenHash };
  }
}